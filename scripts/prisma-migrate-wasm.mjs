// Development-only migration runner using the official, version-pinned Prisma WASM engine.
// It uses Prisma's migration history/checksums. It never resets or drops the target database.
import { config } from "dotenv";
import { SchemaEngine } from "@prisma/schema-engine-wasm";
import { PrismaPg } from "@prisma/adapter-pg";
import { bindMigrationAwareSqlAdapterFactory } from "@prisma/driver-adapter-utils";
import {
  readFileSync,
  readdirSync,
  existsSync,
  mkdirSync,
  writeFileSync,
} from "node:fs";
import { resolve } from "node:path";
config({ path: ".env.local", quiet: true });
const url = process.env.DATABASE_URL;
if (
  process.env.DEVELOPMENT_MODE !== "true" ||
  !url ||
  !["127.0.0.1", "localhost"].includes(new URL(url).hostname)
)
  throw new Error(
    "This runner is restricted to explicitly configured local development databases. Use standard Prisma CLI for authorized production migrations.",
  );
const baseDir = resolve("prisma/migrations"),
  source = readFileSync("prisma/schema.prisma", "utf8");
const filters = { externalTables: [], externalEnums: [] };
const engine = await SchemaEngine.new(
  { datamodels: [["schema.prisma", source]] },
  () => {},
  bindMigrationAwareSqlAdapterFactory(new PrismaPg({ connectionString: url })),
);
function migrationList() {
  return {
    baseDir,
    lockfile: {
      path: "migration_lock.toml",
      content: existsSync(baseDir + "/migration_lock.toml")
        ? readFileSync(baseDir + "/migration_lock.toml", "utf8")
        : null,
    },
    shadowDbInitScript: "",
    migrationDirectories: readdirSync(baseDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => ({
        path: d.name,
        migrationFile: {
          path: "migration.sql",
          content: {
            tag: "ok",
            value: readFileSync(
              baseDir + "/" + d.name + "/migration.sql",
              "utf8",
            ),
          },
        },
      }))
      .sort((a, b) => a.path.localeCompare(b.path)),
  };
}
try {
  if (process.argv.includes("--create-initial")) {
    if (migrationList().migrationDirectories.length)
      throw new Error(
        "Initial migration already exists; refusing to overwrite.",
      );
    const result = await engine.diff({
      from: { tag: "empty" },
      to: {
        tag: "schemaDatamodel",
        files: [{ path: "schema.prisma", content: source }],
      },
      script: true,
      exitCode: false,
      filters,
    });
    const name = "20261013000100_phase3_membership";
    mkdirSync(baseDir + "/" + name);
    writeFileSync(
      baseDir + "/" + name + "/migration.sql",
      result.stdout +
        `\n-- Business invariants not expressible in the Prisma schema.\nCREATE UNIQUE INDEX "application_one_open_per_user" ON "MembershipApplication" ("userId") WHERE status IN ('PENDING', 'RETURNED');\nALTER TABLE "Membership" ADD CONSTRAINT "membership_valid_period" CHECK ("validUntil" > "validFrom");\nALTER TABLE "MembershipApplication" ADD CONSTRAINT "application_positive_version" CHECK (version > 0);\n`,
    );
    writeFileSync(
      baseDir + "/migration_lock.toml",
      'provider = "postgresql"\n',
    );
    console.log("Initial SQL migration generated by Prisma WASM engine.");
  }
  const result = await engine.applyMigrations({
    migrationsList: migrationList(),
    filters,
  });
  console.log("Applied migrations:", result.appliedMigrationNames.length);
} finally {
  engine.free();
}
